DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM pg_namespace WHERE nspname = 'usuarios') THEN
        CREATE SCHEMA usuarios;
    END IF;
END $EF$;


CREATE TABLE usuarios."AspNetRoles" (
    "Id" uuid NOT NULL,
    "Name" character varying(256),
    "NormalizedName" character varying(256),
    "ConcurrencyStamp" text,
    CONSTRAINT "PK_AspNetRoles" PRIMARY KEY ("Id")
);


CREATE TABLE usuarios."AspNetUsers" (
    "Id" uuid NOT NULL,
    "UserName" character varying(256),
    "NormalizedUserName" character varying(256),
    "Email" character varying(256),
    "NormalizedEmail" character varying(256),
    "EmailConfirmed" boolean NOT NULL,
    "PasswordHash" text,
    "SecurityStamp" text,
    "ConcurrencyStamp" text,
    "PhoneNumber" text,
    "PhoneNumberConfirmed" boolean NOT NULL,
    "TwoFactorEnabled" boolean NOT NULL,
    "LockoutEnd" timestamp with time zone,
    "LockoutEnabled" boolean NOT NULL,
    "AccessFailedCount" integer NOT NULL,
    CONSTRAINT "PK_AspNetUsers" PRIMARY KEY ("Id")
);


CREATE TABLE usuarios.personal (
    "Id" uuid NOT NULL,
    "Nombre" character varying(150) NOT NULL,
    "CorreoElectronico" character varying(200) NOT NULL,
    "Activo" boolean NOT NULL,
    CONSTRAINT "PK_personal" PRIMARY KEY ("Id")
);


CREATE TABLE usuarios."AspNetRoleClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "RoleId" uuid NOT NULL,
    "ClaimType" text,
    "ClaimValue" text,
    CONSTRAINT "PK_AspNetRoleClaims" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_AspNetRoleClaims_AspNetRoles_RoleId" FOREIGN KEY ("RoleId") REFERENCES usuarios."AspNetRoles" ("Id") ON DELETE CASCADE
);


CREATE TABLE usuarios."AspNetUserClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "UserId" uuid NOT NULL,
    "ClaimType" text,
    "ClaimValue" text,
    CONSTRAINT "PK_AspNetUserClaims" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_AspNetUserClaims_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES usuarios."AspNetUsers" ("Id") ON DELETE CASCADE
);


CREATE TABLE usuarios."AspNetUserLogins" (
    "LoginProvider" text NOT NULL,
    "ProviderKey" text NOT NULL,
    "ProviderDisplayName" text,
    "UserId" uuid NOT NULL,
    CONSTRAINT "PK_AspNetUserLogins" PRIMARY KEY ("LoginProvider", "ProviderKey"),
    CONSTRAINT "FK_AspNetUserLogins_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES usuarios."AspNetUsers" ("Id") ON DELETE CASCADE
);


CREATE TABLE usuarios."AspNetUserRoles" (
    "UserId" uuid NOT NULL,
    "RoleId" uuid NOT NULL,
    CONSTRAINT "PK_AspNetUserRoles" PRIMARY KEY ("UserId", "RoleId"),
    CONSTRAINT "FK_AspNetUserRoles_AspNetRoles_RoleId" FOREIGN KEY ("RoleId") REFERENCES usuarios."AspNetRoles" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_AspNetUserRoles_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES usuarios."AspNetUsers" ("Id") ON DELETE CASCADE
);


CREATE TABLE usuarios."AspNetUserTokens" (
    "UserId" uuid NOT NULL,
    "LoginProvider" text NOT NULL,
    "Name" text NOT NULL,
    "Value" text,
    CONSTRAINT "PK_AspNetUserTokens" PRIMARY KEY ("UserId", "LoginProvider", "Name"),
    CONSTRAINT "FK_AspNetUserTokens_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES usuarios."AspNetUsers" ("Id") ON DELETE CASCADE
);


CREATE TABLE usuarios.accesos_institucion (
    "Id" uuid NOT NULL,
    "UsuarioId" uuid NOT NULL,
    "InstitucionId" uuid NOT NULL,
    "Rol" character varying(50) NOT NULL,
    CONSTRAINT "PK_accesos_institucion" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_accesos_institucion_personal_UsuarioId" FOREIGN KEY ("UsuarioId") REFERENCES usuarios.personal ("Id") ON DELETE CASCADE
);


CREATE UNIQUE INDEX "IX_accesos_institucion_UsuarioId_InstitucionId" ON usuarios.accesos_institucion ("UsuarioId", "InstitucionId");


CREATE INDEX "IX_AspNetRoleClaims_RoleId" ON usuarios."AspNetRoleClaims" ("RoleId");


CREATE UNIQUE INDEX "RoleNameIndex" ON usuarios."AspNetRoles" ("NormalizedName");


CREATE INDEX "IX_AspNetUserClaims_UserId" ON usuarios."AspNetUserClaims" ("UserId");


CREATE INDEX "IX_AspNetUserLogins_UserId" ON usuarios."AspNetUserLogins" ("UserId");


CREATE INDEX "IX_AspNetUserRoles_RoleId" ON usuarios."AspNetUserRoles" ("RoleId");


CREATE INDEX "EmailIndex" ON usuarios."AspNetUsers" ("NormalizedEmail");


CREATE UNIQUE INDEX "UserNameIndex" ON usuarios."AspNetUsers" ("NormalizedUserName");


CREATE UNIQUE INDEX "IX_personal_CorreoElectronico" ON usuarios.personal ("CorreoElectronico");


